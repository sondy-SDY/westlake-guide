# -*- coding: utf-8 -*-
"""字库引擎素材：16x16 / 2bit 字库 ROM + 文本索引 ROM + 仿真金标准。

文本 ROM 布局（每行 16 字，每页 12 行）：
    0    .. 959   5 页 × 12 行 × 16 字   字幕正文
    960  .. 1103  9 条 × 16 字           右下角状态串

字库 ROM：每个字 16 行 × 32bit（每行 16 像素 × 2bit），地址 = {字码, 行号}。
字码 0 固定为空字，用于补齐和空白。
"""
from pathlib import Path
import json
from PIL import Image, ImageDraw, ImageFont

R = Path(__file__).resolve().parents[1]
FONT = 'C:/Windows/Fonts/msyh.ttc'
CELL = 16
LINES_PER_PAGE = 12
CHARS_PER_LINE = 16
PAGE_STRIDE = LINES_PER_PAGE * CHARS_PER_LINE          # 192
STATUS_BASE = 5 * PAGE_STRIDE                          # 960
STATUS_SLOT = 16

# 状态串最多 9 个字（区宽 316..459 = 9 格），所以 " · " 不留空格
STATUS = [
    '自动轮播·讲解中', '手动浏览·讲解中',
    '自动轮播·已暂停', '手动浏览·已暂停',
    '自动轮播·待播放', '手动浏览·待播放',
    '本页讲解结束', '自动轮播·切换中',
]
REF_STATUS = 5      # 状态槽：手动浏览·待播放


def bits(n):
    return max(1, (n - 1).bit_length())


def main():
    caps = json.load(open(R / 'reports' / 'captions.json', encoding='utf-8'))
    pages = {p['page']: p['lines'] for p in caps['pages']}
    assert max(len(v) for v in pages.values()) <= LINES_PER_PAGE

    text = [0] * (STATUS_BASE + STATUS_SLOT * (len(STATUS) + 1))
    chars = set()
    for i, s in enumerate(STATUS):
        base = STATUS_BASE + (i + 1) * STATUS_SLOT
        for j, ch in enumerate(s.rjust(9)):        # 右对齐到 9 格，末端贴齐字幕带右边
            text[base + j] = ch
            chars.add(ch)
    for page, lines in pages.items():
        for li, ln in enumerate(lines):
            base = (page - 1) * PAGE_STRIDE + li * CHARS_PER_LINE
            for j, ch in enumerate(ln):
                text[base + j] = ch
                chars.add(ch)

    chars.discard(' ')
    char_list = [''] + sorted(chars)
    code = {c: i for i, c in enumerate(char_list)}
    codes = [code.get(c, 0) if c != 0 else 0 for c in text]

    font = ImageFont.truetype(FONT, CELL, index=0)
    glyphs = [None] * len(char_list)
    for i, ch in enumerate(char_list[1:], 1):
        im = Image.new('L', (CELL, CELL), 0)
        ImageDraw.Draw(im).text((CELL // 2, CELL // 2), ch, font=font, fill=255, anchor='mm')
        glyphs[i] = [min(3, (v + 42) // 85) for v in im.get_flattened_data()]

    words = []
    for g in glyphs:
        q = g or [0] * (CELL * CELL)
        for row in range(CELL):
            w = 0
            for c in range(CELL):
                w |= q[row * CELL + c] << (2 * c)
            words.append(w)

    tw, fw = len(codes), len(words)
    tbits, fbits = bits(tw), bits(fw)
    print('chars %d  font %d words (%d bit)  text %d words (%d bit)  page stride %d'
          % (len(char_list) - 1, fw, fbits, tw, tbits, PAGE_STRIDE))

    out = ['// Generated by scripts/gen_text.py.',
           '// 16x16 2bit 字库：每个字 16 行，每行 16 像素 x 2bit = 32 bit，地址 = {码, 行}。',
           '// depth=%d -> %d 位地址' % (fw, fbits),
           'module guide_font_rom(input clk,input [%d:0] a,output reg [31:0] d);' % (fbits - 1),
           'reg [31:0] g[0:%d];' % (fw - 1), 'initial begin']
    for i, w in enumerate(words):
        out.append(" g[%d]=32'h%08x;" % (i, w))
    out += [' end', 'always @(posedge clk) d<=g[a];', 'endmodule', '']
    (R / 'rtl' / 'guide_font_rom.v').write_text('\n'.join(out), encoding='utf-8')

    lay = ['// Generated by scripts/gen_text.py.',
           '// 文本 ROM：每格 16 个 16bit 字码。0..%d 字幕正文（5 页 x 12 行），%d 起状态串。'
           % (STATUS_BASE - 1, STATUS_BASE),
           'module guide_text_rom(input clk,input [%d:0] a,output reg [15:0] d);' % (tbits - 1),
           'reg [15:0] t[0:%d];' % (tw - 1), 'initial begin']
    for i, c in enumerate(codes):
        lay.append(" t[%d]=16'd%d;" % (i, c))
    lay += [' end', 'always @(posedge clk) d<=t[a];', 'endmodule', '']
    (R / 'rtl' / 'guide_text_rom.v').write_text('\n'.join(lay), encoding='utf-8')

    # 仿真金标准：把指定 (页, 行) + 状态槽渲染成 16x640 的 2bit alpha 图
    def emit_ref(page, line, status_idx, fname):
        ref = [[0] * 640 for _ in range(CELL)]

        def stamp(s, x0):
            for i, ch in enumerate(s[:CHARS_PER_LINE]):
                g = glyphs[code.get(ch, 0)] if ch != ' ' else None
                if not g:
                    continue
                for row in range(CELL):
                    for col in range(CELL):
                        a = g[row * CELL + col]
                        if a:
                            ref[row][x0 + i * CELL + col] = a

        stamp(pages[page][line], 24)
        stamp(STATUS[status_idx].rjust(9), 316)
        p = R / 'build' / 'test' / fname
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(chr(10).join('%x' % ref[r][c] for r in range(CELL) for c in range(640)) + chr(10),
                     encoding='utf-8')
        print('  ref %-16s page%d line%d: %s' % (fname, page, line, pages[page][line]))

    # 第 7 帧：还没开始播（手动浏览·待播放），第 0 行
    # 第 8 帧：已经在播（手动浏览·讲解中），时间轴走到第 9 格 -> 第 1 行
    emit_ref(5, 0, REF_STATUS, 'cap_alpha0.hex')
    emit_ref(5, 1, 1, 'cap_alpha1.hex')

    (R / 'reports' / 'text_rom.json').write_text(json.dumps(dict(
        chars=len(char_list) - 1, font_words=fw, font_addr_bits=fbits,
        text_words=tw, text_addr_bits=tbits, status_base=STATUS_BASE,
        page_stride=PAGE_STRIDE, lines_per_page=LINES_PER_PAGE,
        chars_per_line=CHARS_PER_LINE), ensure_ascii=False, indent=1), encoding='utf-8')


if __name__ == '__main__':
    main()
