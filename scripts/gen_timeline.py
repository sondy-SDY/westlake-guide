# -*- coding: utf-8 -*-
"""字幕时间轴：量卡上那条 PCM 的能量包络，按字数等比分配再吸附到真实停顿上。

不重新合成音频、也不要 TTS 的 WordBoundary —— 直接量"到底第几秒开始说下一句"。
硬件侧把时间量化成 0.25 s 一格（48 kHz 计数 12000 个采样），生成一张
  line = tl_rom[{page, slot}]
的查表 ROM，slot 变化是慢信号，不需要任何比较器阵列。
"""
from pathlib import Path
import json
import numpy as np

R = Path(__file__).resolve().parents[1]
PACK = next(p for p in (R.parent / 'westlake_guide_v4', R / 'westlake_guide_v4') if p.exists())
AUDIO = {1: '01_duanqiao', 2: '02_baidi', 3: '03_sudi', 4: '04_huagang', 5: '05_leifengta'}
FR = 480            # 10 ms 一帧
GAP_MIN = 0.15      # 超过 150 ms 的静音才算停顿
SNAP_WIN = 0.70     # 吸附窗口
SLOT = 0.25         # 硬件时间量化
SLOTS = 128
PAGES = 16          # 页号已扩到 4 位


def envelope(path):
    x = np.fromfile(path, dtype='<i2').astype(np.float32)
    k = len(x) // FR
    e = np.sqrt((x[:k * FR].reshape(k, FR) ** 2).mean(axis=1))
    thr = max(np.percentile(e, 20) * 4, np.percentile(e, 95) * 0.04)
    return e > thr


def starts_for(lines, speech):
    idx = np.flatnonzero(speech)
    t0, t1 = idx[0] / 100.0, (idx[-1] + 1) / 100.0

    runs = np.flatnonzero(np.diff(np.concatenate(([0], speech.astype(np.int8), [0]))))
    pauses = []
    for a, b in zip(runs[0::2], runs[1::2]):
        if a == 0:
            continue
        prev = runs[runs < a]
        gap = (a - prev[-1]) / 100.0 if len(prev) else 0.0
        if gap >= GAP_MIN:
            pauses.append(a / 100.0 - gap / 2)

    total = sum(len(s) for s in lines)
    cum, acc, bounds = [], 0, []
    for s in lines[:-1]:
        acc += len(s)
        cum.append(t0 + (t1 - t0) * acc / total)
    used = set()
    for b in cum:
        best, bd = None, SNAP_WIN
        for i, p in enumerate(pauses):
            if i not in used and abs(p - b) < bd:
                best, bd = i, abs(p - b)
        if best is not None:
            used.add(best)
            b = pauses[best]
        bounds.append(b)
    starts = [t0] + bounds
    for i in range(1, len(starts)):
        starts[i] = max(starts[i], starts[i - 1] + max(0.35, 0.11 * len(lines[i - 1])))
    return starts, t1


def main():
    caps = json.load(open(R / 'reports' / 'captions.json', encoding='utf-8'))
    pages = {p['page']: p['lines'] for p in caps['pages']}
    table, lines_of = [], {}
    for page, name in AUDIO.items():
        lines = pages[page]
        starts, t1 = starts_for(lines, envelope(PACK / 'audio' / (name + '.pcm')))
        lines_of[page] = list(zip([round(s, 2) for s in starts], lines))
        for i, s in enumerate(starts):
            end = starts[i + 1] if i + 1 < len(starts) else t1 + 0.4
            table.append(dict(page=page, line=i, start=round(s, 2),
                              end=round(end, 2), text=lines[i]))
        print('page %d: %d 行, %.2f~%.2f s' % (page, len(lines), starts[0], t1))

    # 硬件查表：slot = 0.25 s, 一张 8 页 x 128 格 的 4bit ROM
    rom = [[0] * SLOTS for _ in range(PAGES)]
    for page in range(PAGES):
        st = lines_of.get(page)
        if not st:
            continue
        for s in range(SLOTS):
            t = s * SLOT + SLOT / 2
            n = sum(1 for (a, _) in st if a <= t)
            rom[page][s] = max(0, min(len(st) - 1, n - 1))

    out = ['// Generated by scripts/gen_timeline.py.',
           '// 字幕时间轴查表：地址 = {page[2:0], slot[6:0]}，slot = 0.25 s（48 kHz 计 12000 采样）。',
           '// 数据 = 该时刻应显示的行号（0..11）。',
           'module guide_tl_rom(input clk,input [10:0] a,output reg [3:0] d);',
           'reg [3:0] m[0:2047];', 'initial begin']
    for p in range(PAGES):
        for s in range(SLOTS):
            out.append(" m[%d]=4'd%d;" % (p * SLOTS + s, rom[p][s]))
    out += [' end', 'always @(posedge clk) d<=m[a];', 'endmodule', '']
    (R / 'rtl' / 'guide_tl_rom.v').write_text('\n'.join(out), encoding='utf-8')

    json.dump(dict(slot=SLOT, table=table,
                   rom=dict(pages=PAGES, slots=SLOTS, stride=SLOTS)),
              open(R / 'reports' / 'timeline.json', 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    print('lines %d, rom %dx%d' % (len(table), PAGES, SLOTS))
    for p in (4, 5):
        print('page %d 时间轴:' % p)
        for s, t in lines_of[p]:
            print('   %6.2fs  %s' % (s, t))


if __name__ == '__main__':
    main()
